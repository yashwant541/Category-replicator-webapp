"""Turn a learned system into a standalone Dataiku *recipe script*.

The generated script has the same shape as a hand-written category recipe: a CONFIG block (folder ids,
file-name templates), the learned business logic written out as comments, then a main loop that
    1. reads each selected input file (header row auto-detected),
    2. refreshes the mapping tables from the mapping folder / the input workbook itself,
    3. pre-filters and SPLITS the input into the output sheets,
    4. derives every column per sheet with the learned rules,
    5. writes a values workbook and an Excel-formula workbook (live formulas reference the mapping sheets).

Only data-dependent things are generated (columns, rules, split, mapping tables, sheet names); the engine
code is embedded byte-for-byte so the script is self-contained (pandas + openpyxl + dataiku only).
"""

from __future__ import annotations

import json
import pathlib
from typing import Any, Dict, List

from . import rules as R

LIB = pathlib.Path(__file__).resolve().parents[1]
ORDER = [
    ("replicator_formulas", ["__init__", "formula_translate", "sample_parser", "compute"]),
    ("replicator", ["__init__", "rules", "tables", "learn", "engine", "store", "service"]),
]


def _logic_comment(system: Dict[str, Any]) -> str:
    L: List[str] = []
    f = system.get("filters", {})
    for c in f.get("pre", []) or []:
        L.append("# INPUT FILTER : keep rows where {} {} {}".format(c.get("col"), c.get("op"), c.get("value")))
    sp = f.get("split") or {}
    if sp:
        L.append("# SPLIT        : by column '{}' -> {}".format(
            sp.get("column"), ", ".join(map(str, (sp.get("sheets") or sp.get("map") or {}).keys())) if isinstance(
                sp.get("sheets") or sp.get("map"), dict) else "sheets as learned"))
    sc = system.get("output", {}).get("sheet_columns") or {}
    for sn, cols in sc.items():
        L.append("# SHEET        : {} -> {} columns".format(sn, len(cols)))
    for t, spec in (system.get("tables") or {}).items():
        L.append("# MAPPING      : {} ({} rows)".format(t, len(spec.get("records") or [])))
    for r in system.get("rules", []):
        try:
            d = R.describe(r)
        except Exception:  # noqa: BLE001
            d = r.get("kind", "")
        L.append("# RULE         : {:<28} = {}".format(r["name"], d.replace("\n", " ")))
    return "\n".join(L)


def generate_script(system: Dict[str, Any], *, data_folder: str = "INPUT_FOLDER_ID", mapping_folder: str = "",
                    output_folder: str = "OUTPUT_FOLDER_ID", template_folder: str = "",
                    category: str = "") -> str:
    category = category or system.get("name", "category")
    mod_lines = []
    for pkg, mods in ORDER:
        for m in mods:
            src = (LIB / pkg / (m + ".py")).read_text(encoding="utf-8")
            mod_lines.append("_load(%r, %r, %r)" % (pkg, m, src))
    payload = json.dumps(system, default=str, ensure_ascii=False)
    return _TEMPLATE.format(
        category=category, logic=_logic_comment(system), data_folder=data_folder, mapping_folder=mapping_folder,
        output_folder=output_folder, template_folder=template_folder, slug=_slug(category),
        system=repr(payload), modules="\n".join(mod_lines))


def _slug(s: str) -> str:
    import re
    return re.sub(r"[^A-Za-z0-9]+", "_", s).strip("_").upper() or "CATEGORY"


_TEMPLATE = r'''# -*- coding: utf-8 -*-
"""{category} recipe - GENERATED by the Category Replicator from an example input/mapping/output.
Re-generate it when the layout, the mapping logic or the output formulas change; for new DATA just run it."""
import datetime as dt
import io
import json
import re
import sys
import types
from pathlib import PurePosixPath

import dataiku
import pandas as pd

# =============================================================================
# 1. CONFIGURATION (edit folder ids only)
# =============================================================================
DATA_FOLDER_ID = "{data_folder}"          # input workbooks / csv
MAPPING_FOLDER_ID = "{mapping_folder}"    # optional: refreshed mapping workbooks ("" = use embedded / input sheets)
OUTPUT_FOLDER_ID = "{output_folder}"      # calculated values workbook (one sheet per split)
TEMPLATE_OUTPUT_FOLDER_ID = "{template_folder}"  # formula workbook (live Excel formulas); "" = skip
SELECTION_MANIFEST_PATH = "/_webapp_metadata/selected_inputs.json"
OUTPUT_NAME_TEMPLATE = "{{base}}_{slug}_{{run_id}}.xlsx"
TEMPLATE_NAME_TEMPLATE = "{{base}}_{slug}_TEMPLATE_{{run_id}}.xlsx"
SUPPORTED_EXTENSIONS = (".xlsx", ".xlsm", ".csv")

# =============================================================================
# 2. LEARNED LOGIC (read-only summary; the executable rules are in SYSTEM below)
# =============================================================================
{logic}

SYSTEM = json.loads({system})

# =============================================================================
# 3. ENGINE (embedded library, identical to the Replicator webapp)
# =============================================================================
def _load(pkg, name, src):
    full = pkg if name == "__init__" else pkg + "." + name
    if pkg not in sys.modules:
        p = types.ModuleType(pkg); p.__path__ = []; sys.modules[pkg] = p
    m = sys.modules[pkg] if name == "__init__" else types.ModuleType(full)
    m.__package__ = pkg
    if name != "__init__":
        sys.modules[full] = m; setattr(sys.modules[pkg], name, m)
    exec(compile(src, full, "exec"), m.__dict__)

{modules}

from replicator import engine, service
from replicator.rules import nk
from replicator.tables import read_workbook

# =============================================================================
# 4. FILE HELPERS
# =============================================================================
def _norm(path):
    p = str(path or "").replace("\\", "/").strip()
    return p if p.startswith("/") else "/" + p


def _list(folder):
    return [_norm(p) for p in folder.list_paths_in_partition()]


def _read(folder, path):
    with folder.get_download_stream(path) as s:
        return s.read()


def _manifest(folder):
    try:
        return json.loads(_read(folder, SELECTION_MANIFEST_PATH).decode("utf-8"))
    except Exception:
        return None


def _scope(folder):
    available = _list(folder)
    ok = lambda p: p.lower().endswith(SUPPORTED_EXTENSIONS) and not p.startswith("/_webapp_metadata/")
    man = _manifest(folder)
    run_id = dt.datetime.utcnow().strftime("%Y%m%d_%H%M%S")
    if man:
        run_id = str(man.get("run_id") or run_id)
        sel = [_norm(p) for p in man.get("selected_paths") or []]
        missing = [p for p in sel if p not in available]
        if missing:
            raise ValueError("Selected files do not exist: {{}}".format(missing))
        sel = [p for p in sel if ok(p)]
        if sel:
            return sel, run_id
    paths = sorted(p for p in available if ok(p))
    if not paths:
        raise ValueError("No supported input files in folder {{}}".format(DATA_FOLDER_ID))
    return paths, run_id


def _mapping_overrides(input_name, input_bytes, mapping_folder):
    """Mapping tables refreshed from (a) sheets of the input workbook, (b) the mapping folder.
    A sheet refreshes a table when its name matches the learned table name."""
    sources = [(input_name, input_bytes)]
    if mapping_folder is not None:
        for p in _list(mapping_folder):
            if p.lower().endswith((".xlsx", ".xlsm")) and not p.startswith("/_webapp_metadata/"):
                sources.append((PurePosixPath(p).name, _read(mapping_folder, p)))
    override, used = {{}}, []
    for name, data in sources:
        if not name.lower().endswith((".xlsx", ".xlsm")):
            continue
        for sh in read_workbook(data, name):
            for t in SYSTEM["tables"]:
                if nk(t) == nk(sh["sheet"]):
                    override[t] = sh["df"]
                    used.append("{{}}:{{}}".format(name, sh["sheet"]))
    return override, used

# =============================================================================
# 5. MAIN
# =============================================================================
def main():
    data_f = dataiku.Folder(DATA_FOLDER_ID)
    map_f = dataiku.Folder(MAPPING_FOLDER_ID) if MAPPING_FOLDER_ID else None
    out_f = dataiku.Folder(OUTPUT_FOLDER_ID)
    tpl_f = dataiku.Folder(TEMPLATE_OUTPUT_FOLDER_ID) if TEMPLATE_OUTPUT_FOLDER_ID else None
    paths, run_id = _scope(data_f)
    ok, bad = [], []
    for path in paths:
        name = PurePosixPath(path).name
        try:
            data = _read(data_f, path)
            df, _, used = service._read_inputs(SYSTEM, [(name, data)])      # header auto-detect, canonical names
            override, mapped = _mapping_overrides(name, data, map_f)
            res = engine.apply_system(SYSTEM, df, override)                  # filter -> split -> derive per sheet
            tables = engine.tables_to_frames(SYSTEM, override)
            summary = [("Input", [name]), ("Mapping refreshed from", mapped or ["embedded tables"])]
            base = re.sub(r"\.[^.]+$", "", name)
            values = engine.write_workbook(SYSTEM, res["sheets"], res["work"], summary, False, tables)
            out_name = OUTPUT_NAME_TEMPLATE.format(base=base, run_id=run_id)
            out_f.upload_stream(_norm(out_name), io.BytesIO(values))
            if tpl_f is not None:
                live = engine.write_workbook(SYSTEM, res["sheets"], res["work"], summary, True, tables)
                tpl_f.upload_stream(_norm(TEMPLATE_NAME_TEMPLATE.format(base=base, run_id=run_id)), io.BytesIO(live))
            for n in res["notes"]:
                print("  note:", n)
            if res["rule_errors"]:
                print("  rule errors:", res["rule_errors"])
            ok.append({{"input": name, "rows": res["rows"], "sheets": {{k: len(v) for k, v in res["sheets"].items()}}}})
            print("SUCCESS:", name, "->", ok[-1]["sheets"])
        except Exception as exc:
            bad.append({{"input": name, "error": str(exc)}})
            print("FAILED:", name, "->", exc)
    print("Successful files: {{}} | Failed files: {{}}".format(len(ok), len(bad)))
    if bad:
        raise RuntimeError("One or more input files failed: {{}}".format(bad))


main()
'''
