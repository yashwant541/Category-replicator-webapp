"""Build backend_single.py: one file to paste into the Dataiku webapp Python pane.

The library modules are embedded as source strings and registered as in-memory modules
(`webapp_core.*`, `replicator.*`), so no project-library upload is needed and the code is
byte-for-byte what the tests run.      python build_single.py
"""
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent
LIB = ROOT / "python-lib"
ORDER = [
    ("webapp_core", ["__init__", "formula_translate", "sample_parser", "compute"]),
    ("replicator", ["__init__", "rules", "tables", "learn", "engine", "store", "service"]),
]

out = ['# -*- coding: utf-8 -*-',
       '"""Category Replicator - SINGLE-FILE backend (generated by build_single.py; do not edit).',
       'Paste into the webapp Python pane. Needs only the managed-folder variable REPLICATOR_FOLDER."""',
       'import sys, types',
       '',
       'def _load(pkg, name, src):',
       '    full = pkg if name == "__init__" else pkg + "." + name',
       '    if pkg not in sys.modules:',
       '        p = types.ModuleType(pkg); p.__path__ = []; sys.modules[pkg] = p',
       '    m = sys.modules[pkg] if name == "__init__" else types.ModuleType(full)',
       '    m.__package__ = pkg',
       '    if name != "__init__":',
       '        sys.modules[full] = m; setattr(sys.modules[pkg], name, m)',
       '    exec(compile(src, full, "exec"), m.__dict__)',
       '']
for pkg, mods in ORDER:
    for m in mods:
        src = (LIB / pkg / (m + ".py")).read_text(encoding="utf-8")
        out.append("_load(%r, %r, %r)" % (pkg, m, src))
        out.append("")
backend = (ROOT / "backend" / "backend.py").read_text(encoding="utf-8")
backend = backend.replace("# -*- coding: utf-8 -*-\n", "", 1).replace("from __future__ import annotations\n", "", 1)
out.append(backend)
(ROOT / "backend_single.py").write_text("\n".join(out), encoding="utf-8")
print("wrote backend_single.py", (ROOT / "backend_single.py").stat().st_size // 1024, "KB")
